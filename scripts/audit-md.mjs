// Writes AUDIT.md from content/npm-reports.json so the audit is readable (and crawlable) on github.com.
// Only public findings are listed; secret-pattern matches stay count-only, same as the site.
// Usage: node scripts/audit-md.mjs
import { readFileSync, writeFileSync } from "node:fs";

const SITE = "https://release-shield-app.vercel.app";
const { generatedAt, reports } = JSON.parse(readFileSync(new URL("../content/npm-reports.json", import.meta.url)));
const all = Object.values(reports);
const n = all.length;
const pct = (k) => `${Math.round((k / n) * 100)}%`;
const has = (pred) => all.filter((r) => r.findings.some((f) => pred(f.ruleId))).length;
const bytes = (b) => (b < 1024 ? `${b} B` : b < 1048576 ? `${(b / 1024).toFixed(1)} KB` : `${(b / 1048576).toFixed(1)} MB`);
const num = (x) => x === null ? "—" : new Intl.NumberFormat("en-US", { notation: x >= 10_000 ? "compact" : "standard" }).format(x);
const link = (name) => `${SITE}/npm/${name}?ref=github-audit`;
const cell = (s) => String(s).replace(/\|/g, "\\|");

const maps = has((id) => id.startsWith("source-map"));
const embedded = has((id) => id === "source-map-embedded");
const withheld = all.filter((r) => r.withheld > 0).length;
const clean = all.filter((r) => r.findings.length === 0 && r.withheld === 0).length;
const sizes = all.map((r) => r.totalBytes).sort((a, b) => a - b);
const median = sizes[Math.floor(sizes.length / 2)] ?? 0;
const over1 = sizes.filter((s) => s > 1048576).length;

const flagged = all
  .filter((r) => r.findings.length > 0)
  .sort((a, b) => (b.weeklyDownloads ?? 0) - (a.weeklyDownloads ?? 0) || a.name.localeCompare(b.name));

const rows = flagged.map((r) => {
  // Group per rule: titles already carry "(N files)" when a finding repeats, so strip that and re-sum.
  const byTitle = new Map();
  for (const f of r.findings) {
    const t = f.title.replace(/\s*\(\d+ files?\)$/, "");
    const g = byTitle.get(t) ?? { files: 0, file: f.file };
    g.files += f.occurrences;
    byTitle.set(t, g);
  }
  const what = [...byTitle].map(([t, g]) => (g.files > 1 ? `${t} (${g.files} files)` : `${t} (\`${g.file}\`)`)).join("; ");
  return `| [${cell(r.name)}](${link(r.name)}) | ${r.version} | ${num(r.weeklyDownloads)} | ${bytes(r.totalBytes)} | ${r.fileCount} | ${cell(what)} |`;
});

const md = `# npm tarball audit

The latest published tarball of ${n} npm packages, downloaded and inspected file by file: the exact bytes \`npm install\` fetches, not the git repo. Generated by \`scripts/audit-md.mjs\` from the nightly crawl (last run ${generatedAt.slice(0, 10)}). Full write-up: ${SITE}/report/npm-tarball-audit-2026?ref=github-audit

| | |
|---|---|
| Ship source maps | ${maps} (${pct(maps)}) |
| Inline original source (\`sourcesContent\`) | ${embedded} (${pct(embedded)}) |
| Over 1 MB unpacked | ${over1} (${pct(over1)}) |
| Median unpacked size | ${bytes(median)} |
| Nothing flagged | ${clean} (${pct(clean)}) |
| Matched a secret pattern (not listed, count only) | ${withheld} |

Most findings are hygiene, not leaks: maps, tests, CI and editor config that a \`files\` allowlist in \`package.json\` would have dropped. Why they get in: [the .npmignore trap](${SITE}/guides/npmignore-trap?ref=github-audit), [package.json "files"](${SITE}/guides/package-json-files?ref=github-audit), [source maps in npm packages](${SITE}/guides/source-maps-npm?ref=github-audit).

Check your own package before publishing with the [CLI](README.md#cli) (one file, no install) or the [GitHub Action](README.md#github-action).

## Packages with findings (${flagged.length}), by weekly downloads

| Package | Version | Weekly downloads | Unpacked | Files | Findings |
|---|---|---|---|---|---|
${rows.join("\n")}
`;

writeFileSync(new URL("../AUDIT.md", import.meta.url), md);
console.log(`AUDIT.md: ${n} packages, ${flagged.length} with findings`);
