#!/usr/bin/env node
// Generates the Ed25519 keypair used to sign ReleaseShield license tokens.
//   - private key -> LICENSE_PRIVATE_KEY in .env.local (never committed)
//   - public key  -> lib/license-public-key.ts (committed; embedded in the CLI)
// Rotating the key invalidates every license token issued with the old key.
import { generateKeyPairSync } from "node:crypto";
import { existsSync, readFileSync, writeFileSync, realpathSync } from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const envPath = path.join(root, ".env.local");
const force = process.argv.includes("--force");

const current = existsSync(envPath) ? readFileSync(envPath, "utf8") : "";
if (/^LICENSE_PRIVATE_KEY=/m.test(current) && !force) {
  console.error("LICENSE_PRIVATE_KEY already exists in .env.local. Re-run with --force to rotate (invalidates issued tokens).");
  process.exit(1);
}

const { publicKey, privateKey } = generateKeyPairSync("ed25519");
const priv = privateKey.export({ type: "pkcs8", format: "der" }).toString("base64");
const pub = publicKey.export({ type: "spki", format: "pem" }).toString().trim();

const lines = current.split(/\r?\n/).filter((l) => l.trim() && !l.startsWith("LICENSE_PRIVATE_KEY="));
lines.push(`LICENSE_PRIVATE_KEY=${priv}`);
const target = existsSync(envPath) ? realpathSync(envPath) : envPath;
writeFileSync(target, lines.join("\n") + "\n", { mode: 0o600 });

writeFileSync(
  path.join(root, "lib/license-public-key.ts"),
  `// Generated by scripts/license-keygen.mjs. Public half of the license signing key (safe to commit).\nexport const LICENSE_PUBLIC_KEY_PEM = \`${pub}\`;\n`,
);
console.log(`Wrote LICENSE_PRIVATE_KEY to ${target} and the public key to lib/license-public-key.ts`);
